"""Source-system structure of the ingestion bundle, and the map generated from it.

Layout under ``<bundle>/sources``::

    <source_system>/source.yaml                 kind, owner, deliveries
    <source_system>/<table>.yaml                a spec with no project
    <source_system>/<project>/<table>.yaml      a spec that project is bringing in

``requested_by`` matches the project folder. A spec directly under the source system omits it.
The map is derived only from these files, so it cannot disagree with what is deployed. No
cluster is used.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from lakeflow_framework.config import (
    CATALOG_SETTING,
    CLOUD_PATH,
    DATABASE_KIND,
    EMAIL,
    FILE_KINDS,
    IDENTIFIER,
    SPECS_SETTING,
    VOLUME_PATH,
    ConfigValidationError,
    PipelineConfig,
    email_notifications,
    read_mapping,
    validate_configs,
)
from lakeflow_framework.unity import tag_value

MAP_NAME = "SOURCE_MAP.md"
SOURCE_FILE = "source.yaml"
TRIGGERS = ("file_arrival",)
# cloud_files lands ADLS or S3 files in a raw table. The file kinds keep files in a raw volume.
KINDS = ("cloud_files", *FILE_KINDS, DATABASE_KIND)
ENGINES = ("postgresql", "azure_sql", "sql_server", "db2")
LOAD_METHODS_BY_KIND = {
    "cloud_files": ("autoloader", "copy_into", "ctas"),
    "sftp_files": ("volume_files",),
    "sharepoint_files": ("volume_files",),
    "database": ("database_table",),
}
GENERATED = "# Generated by lakeflow-framework from source.yaml and the table specs. Do not edit."
GENERATED_DIRS = ("pipelines", "resources")
# Specs do not name a catalog. Jobs pass the environment's catalog; checks here use a stand-in.
PLACEHOLDER_CATALOG = "catalog"
WHEEL = "../../framework_lff_lib/dist/*.whl"
# Serverless environment for job tasks: version 4 runs Python 3.12.
ENVIRONMENT_VERSION = "4"
# Fast startup while the framework is being brought up. STANDARD is cheaper and starts in
# minutes, which suits scheduled loads once they run unattended.
PERFORMANCE_TARGET = "PERFORMANCE_OPTIMIZED"
# Each pipeline publishes its event log to framework_meta as <job name><suffix>.
EVENT_LOG_SUFFIX = "_event_log"
WORKFLOW_TAG = "lakeflow_framework_workflow"


@dataclass
class SourceTable:
    config: PipelineConfig
    path: Path
    delivery: str
    requested_by: str


@dataclass
class SourceSystem:
    name: str
    domain: str
    owner: str
    kind: str
    deliveries: dict[str, dict[str, Any]]
    tables: list[SourceTable] = field(default_factory=list)
    raw_volume: dict[str, str] = field(default_factory=dict)
    foreign_catalog: str = ""
    engine: str = ""


def load_sources(
    bundle: Path, catalog: str | None = None, *, allow_frozen: bool = False
) -> list[SourceSystem]:
    """Read and validate every source system. Raises one error listing every problem.

    ``catalog`` is the environment catalog. Generate omits it and uses a stand-in, because a spec
    does not name dev or prod. Deploy passes the target's catalog so the registered names match it.
    """

    root = bundle / "sources"
    errors: list[str] = []
    if not root.is_dir():
        raise ConfigValidationError([f"{root} does not exist"])
    systems: list[SourceSystem] = []
    spec_files: list[tuple[SourceSystem, Path]] = []
    system_dirs = sorted(path for path in root.iterdir() if path.is_dir())
    for folder in system_dirs:
        source_file = folder / SOURCE_FILE
        if not source_file.is_file():
            errors.append(f"{folder}: {SOURCE_FILE} is missing; add it before adding tables")
            continue
        system = _read_source(source_file, folder.name, errors)
        if system is None:
            continue
        systems.append(system)
        spec_files.extend((system, path) for path in _spec_files(folder))
        for project in sorted(path for path in folder.iterdir() if path.is_dir()):
            spec_files.extend((system, path) for path in _spec_files(project))

    for path in [
        folder / SOURCE_FILE for folder in system_dirs if (folder / SOURCE_FILE).is_file()
    ] + [path for _, path in spec_files]:
        if "TODO" in path.read_text(encoding="utf-8"):
            errors.append(f"{path}: replace every TODO before generating")
    if spec_files:
        try:
            configs = validate_configs(
                [path for _, path in spec_files],
                catalog=catalog or PLACEHOLDER_CATALOG,
                allow_frozen=allow_frozen,
            )
        except ConfigValidationError as exc:
            errors.extend(exc.errors)
            configs = []
        if configs and len(configs) == len(spec_files):
            _attach(spec_files, configs, errors)
            errors.extend(_trigger_volume_problems(systems))
    errors.extend(_duplicate_ids(systems))
    if errors:
        raise ConfigValidationError(errors)
    return systems


def registry_rows(bundle: Path, catalog: str) -> list[dict[str, Any]]:
    """Every definition this bundle deploys. registry_sync writes them at deploy.

    Besides each table's rows: one row per source system with its source.yaml, one per schema
    the source writes, and each job's trigger in its workflow row.
    """

    from lakeflow_framework.metadata import definition_rows

    systems = _deployed_systems(bundle, catalog)
    configs = [table.config for system in systems for table in system.tables]
    rows = definition_rows(configs, workflow_details=workflow_details(systems))
    return source_rows(systems, catalog) + rows


def source_rows(systems: list[SourceSystem], catalog: str) -> list[dict[str, Any]]:
    """A ``source_system`` row per source and a ``schema`` row per schema it reads or writes."""

    from lakeflow_framework.metadata import framework_object, utc_now

    recorded = utc_now()
    rows: list[dict[str, Any]] = []
    for system in systems:
        scope = {
            "owner_kind": "source_system",
            "owner": system.name,
            "requested_by": None,
            "delivery": None,
        }
        rows.append(
            framework_object(
                "source_system", system.name, scope, None, None, source_record(system), recorded
            )
        )
        for schema, layers in sorted(source_schemas(system, catalog).items()):
            record = {"catalog": catalog, "layers": layers, "tags": schema_tags(system, layers)}
            rows.append(
                framework_object("schema", schema, scope, system.name, "contains", record, recorded)
            )
    return rows


def source_record(system: SourceSystem) -> dict[str, Any]:
    return {
        "source_system": system.name,
        "domain": system.domain,
        "owner_email": system.owner,
        "source_kind": system.kind,
        "raw_volume": dict(system.raw_volume) or None,
        "foreign_catalog": system.foreign_catalog or None,
        "engine": system.engine or None,
        "deliveries": {
            name: {**detail, "job_name": f"{system.name}_{name}"}
            for name, detail in sorted(system.deliveries.items())
        },
        "requested_by": sorted(
            {table.requested_by for table in system.tables if table.requested_by}
        ),
    }


def source_schemas(system: SourceSystem, catalog: str) -> dict[str, list[str]]:
    """``catalog.schema`` to the layers it holds, for every schema this source uses."""

    layers: dict[str, set[str]] = {}
    if system.raw_volume.get("schema"):
        layers.setdefault(f"{catalog}.{system.raw_volume['schema']}", set()).add("raw")
    for table in system.tables:
        config = table.config
        for layer in config.layers:
            schema = {
                "raw": config.raw_schema,
                "bronze": config.bronze_schema,
                "quarantine": config.quarantine_schema,
            }[layer]
            if schema:
                layers.setdefault(f"{catalog}.{schema}", set()).add(layer)
    return {schema: sorted(found) for schema, found in layers.items()}


def schema_tags(system: SourceSystem, layers: list[str]) -> dict[str, str]:
    """The Unity Catalog tags a source's schema carries. Values are strings."""

    tags = {
        "domain": system.domain,
        "owner": system.name,
        "owner_email": system.owner,
        "source_kind": system.kind,
        "layer": ", ".join(layers),
        "foreign_catalog": system.foreign_catalog,
        "engine": system.engine,
    }
    return {key: value for key, value in tags.items() if value}


def workflow_details(systems: list[SourceSystem]) -> dict[str, dict[str, Any]]:
    """What each generated job is, beyond its pipelines: source, delivery, and trigger."""

    details: dict[str, dict[str, Any]] = {}
    for system in systems:
        for delivery, detail in system.deliveries.items():
            details[f"{system.name}_{delivery}"] = {
                "source_system": system.name,
                "domain": system.domain,
                "owner_email": system.owner,
                "source_kind": system.kind,
                "delivery_detail": dict(detail),
            }
    return details


def deployed_configs(bundle: Path, catalog: str) -> list[PipelineConfig]:
    """Every spec this bundle deploys, named in ``catalog``."""

    return [
        table.config for system in _deployed_systems(bundle, catalog) for table in system.tables
    ]


def _deployed_systems(bundle: Path, catalog: str) -> list[SourceSystem]:
    if not catalog or not re.fullmatch(r"[A-Za-z0-9_-]+", catalog):
        raise ConfigValidationError(["catalog is required"])
    return load_sources(bundle, catalog=catalog)


def render_map(systems: list[SourceSystem]) -> str:
    lines = [
        "# Source ingestion map",
        "",
        f"Generated by `lakeflow-framework generate`. Do not edit; change `{SOURCE_FILE}` or a table",
        "spec and regenerate. `./run.sh bundle:validate` regenerates it first.",
        "",
    ]
    if not systems:
        lines.append("No source systems yet.")
        return "\n".join(lines) + "\n"
    lines += [
        "## Requested by",
        "",
        "| Team or project | Tables | Source systems |",
        "| --- | --- | --- |",
    ]
    requesters: dict[str, list[SourceTable]] = {}
    for system in systems:
        for table in system.tables:
            requesters.setdefault(table.requested_by, []).append(table)
    for name in sorted(requesters):
        tables = requesters[name]
        sources = sorted({table.config.source_system for table in tables})
        label = name or "—"
        lines.append(f"| {label} | {len(tables)} | {', '.join(sources)} |")
    for system in sorted(systems, key=lambda item: (item.domain, item.name)):
        lines += _system_section(system)
    return "\n".join(lines) + "\n"


def render_files(systems: list[SourceSystem]) -> dict[str, str]:
    """Every generated file, by path under the bundle: the map, and per delivery one pipeline
    source file, one pipeline resource, and one job. All come from the same model, so the map
    always describes what is deployed."""

    files = {MAP_NAME: render_map(systems)}
    for system in systems:
        by_delivery: dict[str, list[SourceTable]] = {}
        for table in system.tables:
            by_delivery.setdefault(table.delivery, []).append(table)
        for delivery, tables in sorted(by_delivery.items()):
            tables.sort(key=lambda item: item.config.pipeline_id)
            name = f"{system.name}_{delivery}"
            files[f"pipelines/{name}.py"] = _pipeline_source(tables)
            files[f"resources/{name}.pipeline.yml"] = _yaml(_pipeline_resource(name, tables))
            files[f"resources/{name}.job.yml"] = _yaml(_job_resource(system, delivery, tables))
    return files


def generate(bundle: Path, check: bool = False, *, allow_frozen: bool = False) -> list[str]:
    """Write the generated files, and remove generated files no source asks for.

    With ``check``, change nothing. Returns the paths that were (or would be) out of date, empty
    when the bundle already matches its sources. Files without the generated marker are never
    touched. ``allow_frozen`` is for tests of the frozen load methods.
    """

    files = render_files(load_sources(bundle, allow_frozen=allow_frozen))
    stale = write_generated(bundle, files, check)
    for relative in _generated_files(bundle):
        if relative not in files:
            stale.append(relative)
            if not check:
                (bundle / relative).unlink()
    return sorted(stale)


def write_generated(root: Path, files: dict[str, str], check: bool) -> list[str]:
    """Write each file whose text differs from disk. With ``check``, change nothing.

    Returns the paths that were out of date, in the order given.
    """

    stale: list[str] = []
    for relative, text in files.items():
        target = root / relative
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            stale.append(relative)
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
    return stale


def identifier_problems(values: dict[str, str]) -> list[str]:
    return [
        f"{key} must be an identifier, not {value!r}"
        for key, value in values.items()
        if not IDENTIFIER.match(value)
    ]


def refuse_existing(target: Path) -> None:
    if target.exists():
        raise ConfigValidationError([f"{target} already exists"])


def _generated_files(bundle: Path) -> list[str]:
    found: list[str] = []
    for folder in GENERATED_DIRS:
        for path in sorted((bundle / folder).glob("*")):
            if path.suffix not in {".py", ".yml"} or not path.is_file():
                continue
            if path.read_text(encoding="utf-8").startswith(GENERATED):
                found.append(f"{folder}/{path.name}")
    return found


def _pipeline_source(tables: list[SourceTable]) -> str:
    ids = ", ".join(f'"{table.config.pipeline_id}"' for table in tables)
    lines = [
        GENERATED,
        "from lakeflow_framework import build_pipelines",
        "",
        f"build_pipelines([{ids}])",
    ]
    return "\n".join(lines) + "\n"


def _uploaded_wheel() -> str:
    """Where `bundle deploy` puts this package's wheel in the workspace."""

    from importlib.metadata import version

    return (
        f"${{workspace.artifact_path}}/.internal/"
        f"lakeflow_framework-{version('lakeflow_framework')}-py3-none-any.whl"
    )


def _spec_paths(tables: list[SourceTable]) -> list[str]:
    return ["${workspace.file_path}/" + _spec_rel(table.path) for table in tables]


def _pipeline_resource(name: str, tables: list[SourceTable]) -> dict[str, Any]:
    return {
        "resources": {
            "pipelines": {
                # Resource keys must be unique across resource types, and the job uses `name`.
                f"{name}_pipeline": {
                    "name": name,
                    "catalog": "${var.catalog}",
                    "schema": "framework_meta",
                    "serverless": True,
                    "channel": "current",
                    "continuous": False,
                    # framework_metrics finds the logs by this name and reads the job name from it.
                    "event_log": {
                        "catalog": "${var.catalog}",
                        "schema": "framework_meta",
                        "name": f"{name}{EVENT_LOG_SUFFIX}",
                    },
                    # build_pipelines reads these deployed specs, so a run does not wait on the
                    # registry.
                    "configuration": {
                        SPECS_SETTING: ",".join(_spec_paths(tables)),
                        CATALOG_SETTING: "${var.catalog}",
                    },
                    "libraries": [{"file": {"path": f"../pipelines/{name}.py"}}],
                    # A pipeline does not accept whl libraries, and the CLI does not rewrite a
                    # local path in its pip dependencies, so name the wheel `bundle deploy` uploads.
                    "environment": {"dependencies": [_uploaded_wheel()]},
                }
            }
        }
    }


def _job_resource(system: SourceSystem, delivery: str, tables: list[SourceTable]) -> dict[str, Any]:
    name = f"{system.name}_{delivery}"
    configs = [table.config for table in tables]
    batch_paths = [
        path
        for path, config in zip(_spec_paths(tables), configs)
        if config.load_method in {"copy_into", "ctas"}
    ]
    tasks: list[dict[str, Any]] = []
    if batch_paths:
        tasks.append(
            {
                "task_key": "batch_load",
                "environment_key": "framework_env",
                "spark_python_task": {
                    "python_file": "../src/run_batch.py",
                    "parameters": ["--catalog", "${var.catalog}", *batch_paths],
                },
            }
        )
    refresh: dict[str, Any] = {"task_key": "refresh_pipeline"}
    if tasks:
        refresh["depends_on"] = [{"task_key": "batch_load"}]
    refresh["pipeline_task"] = {"pipeline_id": f"${{resources.pipelines.{name}_pipeline.id}}"}
    tasks.append(refresh)

    # Deployed names carry a dev or prod prefix, so the run views join system tables on this tag.
    job: dict[str, Any] = {"name": name, "tags": job_tags(system, delivery, configs)}
    notes = email_notifications(configs)
    if notes:
        job["email_notifications"] = {**notes, "no_alert_for_skipped_runs": True}
    detail = system.deliveries[delivery]
    if detail.get("schedule"):
        job["schedule"] = {"quartz_cron_expression": detail["schedule"], "timezone_id": "UTC"}
    elif system.kind in FILE_KINDS:
        # Validation guarantees the delivery's tables read one volume.
        schema, volume = _volume_of(configs[0])
        job["trigger"] = {"file_arrival": {"url": f"/Volumes/${{var.catalog}}/{schema}/{volume}/"}}
    else:
        job["trigger"] = {"file_arrival": {"url": detail["path"]}}
    if batch_paths:
        job["environments"] = [
            {
                "environment_key": "framework_env",
                "spec": {"environment_version": ENVIRONMENT_VERSION, "dependencies": [WHEEL]},
            }
        ]
    job["performance_target"] = PERFORMANCE_TARGET
    job["tasks"] = tasks
    return {"resources": {"jobs": {name: job}}}


def job_tags(system: SourceSystem, delivery: str, configs: list[PipelineConfig]) -> dict[str, str]:
    """Job tags: the workflow tag the run views join on, and the job's source details."""

    tags = {
        WORKFLOW_TAG: f"{system.name}_{delivery}",
        "domain": system.domain,
        "owner": system.name,
        "owner_email": system.owner,
        "source_kind": system.kind,
        "delivery": delivery,
        "requested_by": ", ".join(sorted({c.requested_by for c in configs if c.requested_by})),
        "data_domain": ", ".join(sorted({c.data_domain for c in configs if c.data_domain})),
    }
    return {key: tag_value(value) for key, value in tags.items() if tag_value(value)}


def _yaml(document: dict[str, Any]) -> str:
    body = yaml.safe_dump(document, sort_keys=False, default_flow_style=False, width=1000)
    return f"{GENERATED}\n{body}"


def _volume_of(config: PipelineConfig) -> tuple[str, str]:
    """The (schema, volume) a file table reads, from /Volumes/<catalog>/<schema>/<volume>/..."""

    parts = [part for part in config.path.split("/") if part]
    return parts[2], parts[3]


def _trigger_volume_problems(systems: list[SourceSystem]) -> list[str]:
    """A file-arrival trigger watches one volume, so a delivery's tables must read the same one."""

    problems: list[str] = []
    for system in systems:
        if system.kind not in FILE_KINDS:
            continue
        for delivery, detail in sorted(system.deliveries.items()):
            if detail.get("schedule"):
                continue
            volumes = sorted(
                {
                    ".".join(_volume_of(table.config))
                    for table in system.tables
                    if table.delivery == delivery
                }
            )
            if len(volumes) > 1:
                problems.append(
                    f"sources/{system.name}: delivery {delivery} fires on one volume, but its "
                    f"tables read {', '.join(volumes)}; give each volume its own delivery, "
                    "or run the delivery on a schedule"
                )
    return problems


def _read_source(path: Path, name: str, errors: list[str]) -> SourceSystem | None:
    document = read_mapping(path, errors)
    if document is None:
        return None
    found: list[str] = []
    if document.get("source_system") != name:
        found.append(f"{path}: source_system must be {name}, the folder name")
    domain = str(document.get("domain") or "")
    if not IDENTIFIER.match(domain):
        found.append(f"{path}: domain must be an identifier")
    owner = str(document.get("owner") or "")
    if not EMAIL.match(owner):
        found.append(f"{path}: owner must be an email address")
    kind = str(document.get("kind") or "")
    if kind not in KINDS:
        found.append(f"{path}: kind must be one of {', '.join(KINDS)}")
    volume = document.get("raw_volume") if isinstance(document.get("raw_volume"), dict) else {}
    foreign_catalog = str(document.get("foreign_catalog") or "")
    engine = str(document.get("engine") or "")
    if kind in FILE_KINDS:
        # source.yaml names the schema. Each table names its volume next to its file settings;
        # a volume here is only a default for tables that do not name one.
        if not IDENTIFIER.match(str(volume.get("schema") or "")):
            found.append(f"{path}: a {kind} source needs raw_volume with a schema")
        if volume.get("volume") and not IDENTIFIER.match(str(volume["volume"])):
            found.append(f"{path}: raw_volume.volume must be an identifier")
    if kind == DATABASE_KIND:
        if not IDENTIFIER.match(foreign_catalog):
            found.append(f"{path}: a database source needs foreign_catalog, the federated catalog")
        if engine and engine not in ENGINES:
            found.append(f"{path}: engine must be one of {', '.join(ENGINES)}")
    if "defaults" in document:
        found.append(
            f"{path}: defaults is not supported; owner, sensitivity, and notify belong in each "
            "table spec, because one source system can deliver files of different kinds"
        )
    if "fetch" in document or any(
        isinstance(item, dict) and "fetch" in item
        for item in (document.get("deliveries") or {}).values()
    ):
        found.append(
            f"{path}: fetch is not built; deliver files to the raw volume with another process"
        )
    deliveries = document.get("deliveries")
    if not isinstance(deliveries, dict) or not deliveries:
        found.append(f"{path}: deliveries must list at least one delivery")
        deliveries = {}
    for delivery, detail in deliveries.items():
        if not IDENTIFIER.match(str(delivery)):
            found.append(f"{path}: delivery {delivery} must be an identifier")
        detail = detail if isinstance(detail, dict) else {}
        schedule, trigger = detail.get("schedule"), detail.get("trigger")
        if bool(schedule) == bool(trigger):
            found.append(f"{path}: delivery {delivery} needs exactly one of schedule or trigger")
        if trigger and trigger not in TRIGGERS:
            found.append(
                f"{path}: delivery {delivery} trigger must be one of {', '.join(TRIGGERS)}"
            )
        if trigger and kind == DATABASE_KIND:
            found.append(f"{path}: a database delivery runs on a schedule, not a {trigger}")
        if trigger == "file_arrival" and kind == "cloud_files":
            arrival = str(detail.get("path") or "")
            if not (CLOUD_PATH.match(arrival) or VOLUME_PATH.match(arrival)):
                found.append(
                    f"{path}: delivery {delivery} needs a path that starts with abfss:// or s3://, "
                    "or a /Volumes path"
                )
    errors.extend(found)
    if found:
        return None
    return SourceSystem(
        name,
        domain,
        owner,
        kind,
        {str(k): dict(v) for k, v in deliveries.items()},
        raw_volume={
            "schema": str(volume.get("schema") or ""),
            "volume": str(volume.get("volume") or ""),
        },
        foreign_catalog=foreign_catalog,
        engine=engine,
    )


def _project_folder(path: Path) -> str | None:
    """The project directory a spec is in, or none when it sits next to source.yaml."""

    if (path.parent / SOURCE_FILE).is_file():
        return None
    return path.parent.name


def _spec_rel(path: Path) -> str:
    parts = path.parts
    return "/".join(parts[parts.index("sources") :])


def _spec_files(folder: Path) -> list[Path]:
    return sorted(
        path for path in [*folder.glob("*.yaml"), *folder.glob("*.yml")] if path.name != SOURCE_FILE
    )


def _attach(
    spec_files: list[tuple[SourceSystem, Path]],
    configs: list[PipelineConfig],
    errors: list[str],
) -> None:
    for (system, path), config in zip(spec_files, configs):
        document = config.document
        if config.domain != system.domain:
            errors.append(f"{path}: domain is {config.domain}; this folder holds {system.domain}")
        if config.source_system != system.name:
            errors.append(
                f"{path}: source_to_raw.source.system is {config.source_system}; "
                f"this folder holds {system.name}"
            )
        requested_by = str(document.get("requested_by") or "")
        project = _project_folder(path)
        if document.get("project") and not document.get("requested_by"):
            errors.append(f"{path}: project is replaced by requested_by in specs under sources/")
        elif project is None and requested_by:
            errors.append(
                f"{path}: requested_by belongs in {system.name}/{requested_by}/, "
                "not next to source.yaml"
            )
        elif project is not None and requested_by != project:
            errors.append(f"{path}: requested_by must be {project}, the folder the spec is in")
        delivery = str(document.get("delivery") or "")
        if not delivery and len(system.deliveries) == 1:
            delivery = next(iter(system.deliveries))
        if delivery not in system.deliveries:
            known = ", ".join(sorted(system.deliveries))
            errors.append(f"{path}: delivery must be one of {known}")
        allowed = LOAD_METHODS_BY_KIND[system.kind]
        if config.load_method not in allowed:
            errors.append(
                f"{path}: a {system.kind} source loads with {', '.join(allowed)}; "
                f"this spec uses {config.load_method}"
            )
        if not config.pipeline_id.startswith(f"{system.name}_"):
            errors.append(f"{path}: pipeline_id must start with {system.name}_")
        if config.job_name and config.job_name != f"{system.name}_{delivery}":
            errors.append(
                f"{path}: job_name must be {system.name}_{delivery}, the generated job, or omitted"
            )
        system.tables.append(SourceTable(config, path, delivery, requested_by))


def _duplicate_ids(systems: list[SourceSystem]) -> list[str]:
    seen: dict[str, Path] = {}
    errors: list[str] = []
    for system in systems:
        for table in system.tables:
            first = seen.get(table.config.pipeline_id)
            if first is not None:
                errors.append(
                    f"{table.path}: pipeline_id {table.config.pipeline_id} is already used by {first}"
                )
            seen[table.config.pipeline_id] = table.path
    return errors


def _system_section(system: SourceSystem) -> list[str]:
    lines = [
        "",
        f"## {system.domain} / {system.name}",
        "",
        f"Kind: {system.kind}. Owner: {system.owner}.",
    ]
    if system.kind in FILE_KINDS:
        lines.append(
            f"Raw schema: `{system.raw_volume['schema']}`. Files land in a volume here as "
            "delivered, and bronze reads them from it. Each table names its volume."
        )
    if system.kind == DATABASE_KIND:
        engine = f" ({system.engine})" if system.engine else ""
        lines.append(
            f"Foreign catalog: `{system.foreign_catalog}`{engine}. Tables load straight to bronze."
        )
    lines += ["", "| Delivery | When |", "| --- | --- |"]
    for name in sorted(system.deliveries):
        detail = system.deliveries[name]
        when = f"cron `{detail['schedule']}`" if detail.get("schedule") else str(detail["trigger"])
        lines.append(f"| {name} | {when} |")
    lines += [
        "",
        "| Table | Delivery | Requested by | Reads | Load | Bronze | Technical owner |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for table in sorted(system.tables, key=lambda item: item.config.pipeline_id):
        config = table.config
        lines.append(
            f"| {config.pipeline_id} | {table.delivery} | {table.requested_by or '—'} | "
            f"{_reads(config)} | {config.load_method} | "
            f"{config.bronze_schema}.{config.bronze_table} | "
            f"{config.technical_owner} |"
        )
    lines += ["", "```mermaid", "flowchart LR"]
    for name in sorted(system.deliveries):
        lines.append(f"  {node_id(system.name, name)}{{{{{name}}}}}")
    for table in sorted(system.tables, key=lambda item: item.config.pipeline_id):
        config = table.config
        lines.append(
            f"  {node_id(system.name, table.delivery)} -->|{table.requested_by or system.name}| "
            f"{node_id(config.pipeline_id)}[{config.pipeline_id}]"
        )
        bronze = node_id(config.bronze_schema, config.bronze_table)
        lines.append(
            f"  {node_id(config.pipeline_id)} --> {bronze}"
            f"[{config.bronze_schema}.{config.bronze_table}]"
        )
    lines.append("```")
    return lines


def new_source(
    bundle: Path, domain: str, source_system: str, *, owner: str, kind: str, delivery: str
) -> Path:
    """Create ``source.yaml`` for a new source system, in the folder the layout expects."""

    _names({"domain": domain, "source_system": source_system, "delivery": delivery})
    if kind not in KINDS:
        raise ConfigValidationError([f"kind must be one of {', '.join(KINDS)}"])
    if not EMAIL.match(owner):
        raise ConfigValidationError(["owner must be an email address"])
    target = bundle / "sources" / source_system / SOURCE_FILE
    refuse_existing(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    head = f"source_system: {source_system}\ndomain: {domain}\nowner: {owner}\nkind: {kind}\n\n"
    if kind in FILE_KINDS:
        body = (
            "# Files land in volumes of this schema as delivered. Bronze reads them from there.\n"
            "# Each table spec names its own volume, next to its file settings.\n"
            f"raw_volume:\n  schema: {source_system}_raw\n\n"
            "# A delivery fires when files arrive in the volume its tables read, or on a\n"
            "# schedule instead:\n"
            '#   schedule: "<quartz cron>"\n'
            f"deliveries:\n  {delivery}:\n    trigger: file_arrival\n"
        )
    elif kind == DATABASE_KIND:
        body = (
            "# The catalog that exposes the database (Lakehouse Federation).\n"
            "foreign_catalog: TODO\n"
            f"engine: postgresql  # one of {', '.join(ENGINES)}\n\n"
            f'deliveries:\n  {delivery}:\n    schedule: "0 0 2 * * ?"\n'
        )
    else:
        body = (
            f"deliveries:\n  {delivery}:\n    trigger: file_arrival\n"
            f"    path: abfss://landing@TODO.dfs.core.windows.net/{source_system}/\n"
        )
    target.write_text(head + body, encoding="utf-8")
    return target


def new_table(
    bundle: Path,
    domain: str,
    source_system: str,
    table: str,
    *,
    requested_by: str | None,
    delivery: str | None,
) -> Path:
    """Create a table spec under the project, or next to source.yaml when there is no project."""

    _names({"domain": domain, "source_system": source_system, "table": table})
    if requested_by:
        _names({"requested_by": requested_by})
    folder = bundle / "sources" / source_system
    source_file = folder / SOURCE_FILE
    if not source_file.exists():
        raise ConfigValidationError(
            [f"{source_file} is missing; run new-source for {source_system} first"]
        )
    found = yaml.safe_load(source_file.read_text(encoding="utf-8")) or {}
    deliveries = sorted((found.get("deliveries") or {}).keys())
    if delivery is None:
        if len(deliveries) != 1:
            raise ConfigValidationError(
                [
                    f"{source_system} has several deliveries ({', '.join(deliveries)}); pass --delivery"
                ]
            )
        delivery = deliveries[0]
    elif delivery not in deliveries:
        raise ConfigValidationError([f"delivery must be one of {', '.join(deliveries)}"])
    owner = str(found.get("owner") or "TODO@example.com")
    target_dir = folder / requested_by if requested_by else folder
    target_dir.mkdir(parents=True, exist_ok=True)
    target = target_dir / f"{source_system}_{table}.yaml"
    refuse_existing(target)
    kind = str(found.get("kind") or "")
    template = {
        "database": _DATABASE_TEMPLATE,
        "sftp_files": _VOLUME_TEMPLATE,
        "sharepoint_files": _VOLUME_TEMPLATE,
    }.get(kind, _TABLE_TEMPLATE)
    volume = found.get("raw_volume") if isinstance(found.get("raw_volume"), dict) else {}
    target.write_text(
        template.format(
            source=source_system,
            table=table,
            domain=domain,
            owner=owner,
            requested_by=requested_by or source_system,
            requested_by_line=(f"requested_by: {requested_by}\n" if requested_by else ""),
            delivery=delivery,
            delivery_line=(f"delivery: {delivery}\n" if len(deliveries) > 1 else ""),
            volume=str(volume.get("volume") or "TODO_volume"),
        ),
        encoding="utf-8",
    )
    return target


