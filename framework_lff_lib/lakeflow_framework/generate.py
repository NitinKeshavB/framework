def render_map(systems: list[SourceSystem]) -> str:
    lines = [
        "# Source ingestion map",
        "",
        f"Generated by `lakeflow-framework generate`. Do not edit; change `{SOURCE_FILE}` or a table",
        "spec and regenerate. `./run.sh bundle:validate` regenerates it first.",
        "",
    ]
    if not systems:
        lines.append("No source systems yet.")
        return "\n".join(lines) + "\n"
    lines += [
        "## Requested by",
        "",
        "| Team or project | Tables | Source systems |",
        "| --- | --- | --- |",
    ]
    requesters: dict[str, list[SourceTable]] = {}
    for system in systems:
        for table in system.tables:
            requesters.setdefault(table.requested_by, []).append(table)
    for name in sorted(requesters):
        tables = requesters[name]
        sources = sorted({table.config.source_system for table in tables})
        label = name or "—"
        lines.append(f"| {label} | {len(tables)} | {', '.join(sources)} |")
    for system in sorted(systems, key=lambda item: (item.domain, item.name)):
        lines += _system_section(system)
    return "\n".join(lines) + "\n"


def render_files(systems: list[SourceSystem]) -> dict[str, str]:
    """Every generated file under the bundle.

    ``SOURCE_MAP.md`` at the root (committed). Under ``.build/``: one pipeline entrypoint,
    pipeline resource, job resource, and ``manifests/<delivery>.json`` per delivery.
    """

    files = {MAP_NAME: render_map(systems)}
    for system in systems:
        by_delivery: dict[str, list[SourceTable]] = {}
        for table in system.tables:
            by_delivery.setdefault(table.delivery, []).append(table)
        for delivery, tables in sorted(by_delivery.items()):
            tables.sort(key=lambda item: item.config.pipeline_id)
            name = f"{system.name}_{delivery}"
            manifest = {
                "delivery": name,
                "spec_version": 1,
                "pipelines": [
                    {
                        "pipeline_id": table.config.pipeline_id,
                        "content_hash": table.config.content_hash(),
                        "config": table.config.canonical(),
                    }
                    for table in tables
                ],
            }
            manifest["content_hash"] = _manifest_hash(manifest["pipelines"])
            files[f"{BUILD_DIR}/manifests/{name}.json"] = (
                json.dumps(manifest, indent=2, sort_keys=True) + "\n"
            )
            files[f"{BUILD_DIR}/pipelines/{name}.py"] = _pipeline_source(tables)
            files[f"{BUILD_DIR}/resources/{name}.pipeline.yml"] = _yaml(
                _pipeline_resource(name, tables, run_as=system.run_as)
            )
            files[f"{BUILD_DIR}/resources/{name}.job.yml"] = _yaml(
                _job_resource(system, delivery, tables)
            )
    return files


def _manifest_hash(pipelines: list[dict[str, Any]]) -> str:
    import json

    payload = json.dumps(pipelines, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def generate(bundle: Path, check: bool = False, *, allow_frozen: bool = False) -> list[str]:
    """Write generated files, and remove generated files no source asks for.

    With ``check``, only drift-check ``SOURCE_MAP.md`` (and still validate every spec via
    ``load_sources``). Resource YAML under ``.build/`` is regenerated on every deploy and is
    not a PR conflict surface. ``allow_frozen`` is for tests of the frozen load methods.
    """

    files = render_files(load_sources(bundle, allow_frozen=allow_frozen))
    if check:
        return write_generated(bundle, {MAP_NAME: files[MAP_NAME]}, check=True)
    stale = write_generated(bundle, files, check=False)
    for relative in _generated_files(bundle):
        if relative not in files:
            stale.append(relative)
            (bundle / relative).unlink(missing_ok=True)
    return sorted(stale)


def write_generated(root: Path, files: dict[str, str], check: bool) -> list[str]:
    """Write each file whose text differs from disk. With ``check``, change nothing.

    Returns the paths that were out of date, in the order given.
    """

    stale: list[str] = []
    for relative, text in files.items():
        target = root / relative
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            stale.append(relative)
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
    return stale


def _generated_files(bundle: Path) -> list[str]:
    found: list[str] = []
    for folder in GENERATED_DIRS:
        root = bundle / folder
        if not root.is_dir():
            continue
        for path in sorted(root.glob("*")):
            if not path.is_file() or path.suffix not in {".py", ".yml", ".json"}:
                continue
            if path.suffix == ".json" or path.read_text(encoding="utf-8").startswith(GENERATED):
                found.append(f"{folder}/{path.name}")
    return found


def _pipeline_source(tables: list[SourceTable]) -> str:
    ids = ", ".join(f'"{table.config.pipeline_id}"' for table in tables)
    lines = [
        GENERATED,
        "from lakeflow_framework import build_pipelines",
        "",
        f"build_pipelines([{ids}])",
    ]
    return "\n".join(lines) + "\n"


def _uploaded_wheel() -> str:
    """Where `bundle deploy` puts this package's wheel in the workspace.

    Uses ``PACKAGE_VERSION`` (not ``importlib.metadata``) so ``generate:check`` does not
    flap when a developer has a stale editable install.
    """

    return (
        f"${{workspace.artifact_path}}/.internal/"
        f"lakeflow_framework-{PACKAGE_VERSION}-py3-none-any.whl"
    )


def _spec_paths(tables: list[SourceTable]) -> list[str]:
    return ["${workspace.file_path}/" + _spec_rel(table.path) for table in tables]


def _pipeline_resource(name: str, tables: list[SourceTable], *, run_as: str = "") -> dict[str, Any]:
    pipeline: dict[str, Any] = {
        "name": name,
        "catalog": "${var.catalog}",
        "schema": "framework_meta",
        "serverless": True,
        "channel": "current",
        "continuous": False,
        # framework_runs finds the log by this name (the pipeline's own hook reads its events live).
        "event_log": {
            "catalog": "${var.catalog}",
            "schema": "framework_events",
            "name": f"{name}{EVENT_LOG_SUFFIX}",
        },
        # One compiled manifest for the delivery (preferred over a comma-joined specs list).
        "configuration": {
            MANIFEST_SETTING: f"${{workspace.file_path}}/{BUILD_DIR}/manifests/{name}.json",
            CATALOG_SETTING: "${var.catalog}",
            # A production pipeline restarts a failed update by itself. A file blocked by a fail
            # rule fails the update on purpose, and the restart finds the file already read and
            # nothing new, so it would finish and the run would look like a success.
            "pipelines.numUpdateRetryAttempts": "0",
        },
        "libraries": [{"file": {"path": f"../pipelines/{name}.py"}}],
        # A pipeline does not accept whl libraries, and the CLI does not rewrite a
        # local path in its pip dependencies, so name the wheel `bundle deploy` uploads.
        "environment": {"dependencies": [_uploaded_wheel()]},
    }
    if run_as:
        pipeline["run_as"] = {"service_principal_name": run_as}
    return {
        "resources": {
            "pipelines": {
                # Resource keys must be unique across resource types, and the job uses `name`.
                f"{name}_pipeline": pipeline
            }
        }
    }


def _job_resource(system: SourceSystem, delivery: str, tables: list[SourceTable]) -> dict[str, Any]:
    name = f"{system.name}_{delivery}"
    configs = [table.config for table in tables]
    batch_paths = [
        path
        for path, config in zip(_spec_paths(tables), configs, strict=True)
        if config.load_method in {"copy_into", "ctas"}
    ]
    tasks: list[dict[str, Any]] = []
    if batch_paths:
        tasks.append(
            {
                "task_key": "batch_load",
                "environment_key": "framework_env",
                "spark_python_task": {
                    "python_file": "../../src/run_batch.py",
                    "parameters": ["--catalog", "${var.catalog}", *batch_paths],
                },
            }
        )
    refresh: dict[str, Any] = {"task_key": "refresh_pipeline"}
    if tasks:
        refresh["depends_on"] = [{"task_key": "batch_load"}]
    refresh["pipeline_task"] = {"pipeline_id": f"${{resources.pipelines.{name}_pipeline.id}}"}
    tasks.append(refresh)
    # No recording task follows. The pipeline records its own load counts, status, and error once
    # per update (an event hook, see pipeline_metrics). The hourly framework_runs job records the
    # job runs themselves, including runs that never reached the pipeline.

    # Deployed names carry a dev or prod prefix, so the run views join system tables on this tag.
    job: dict[str, Any] = {"name": name, "tags": job_tags(system, delivery, configs)}
    notes = email_notifications(configs)
    if notes:
        job["email_notifications"] = {**notes, "no_alert_for_skipped_runs": True}
    detail = system.deliveries[delivery]
    if detail.get("schedule"):
        job["schedule"] = {"quartz_cron_expression": detail["schedule"], "timezone_id": "UTC"}
    elif system.kind in FILE_KINDS:
        # Validation guarantees the delivery's tables read one volume.
        schema, volume = _volume_of(configs[0])
        job["trigger"] = {"file_arrival": {"url": f"/Volumes/${{var.catalog}}/{schema}/{volume}/"}}
    else:
        job["trigger"] = {"file_arrival": {"url": detail["path"]}}
    if batch_paths:
        job["environments"] = [
            {
                "environment_key": "framework_env",
                "spec": {"environment_version": ENVIRONMENT_VERSION, "dependencies": [WHEEL]},
            }
        ]
    job["performance_target"] = system.performance_target or PERFORMANCE_TARGET
    job["tasks"] = tasks
    if system.run_as:
        job["run_as"] = {"service_principal_name": system.run_as}
    return {"resources": {"jobs": {name: job}}}


def job_tags(system: SourceSystem, delivery: str, configs: list[PipelineConfig]) -> dict[str, str]:
    """Job tags: the workflow tag the run views join on, and the job's source details."""

    tags = {
        WORKFLOW_TAG: f"{system.name}_{delivery}",
        "domain": system.domain,
        "owner": system.name,
        "owner_email": system.owner,
        "source_kind": system.kind,
        "delivery": delivery,
        "requested_by": ", ".join(sorted({c.requested_by for c in configs if c.requested_by})),
        "data_domain": ", ".join(sorted({c.data_domain for c in configs if c.data_domain})),
    }
    return {key: tag_value(value) for key, value in tags.items() if tag_value(value)}


def _yaml(document: dict[str, Any]) -> str:
    body = yaml.safe_dump(document, sort_keys=False, default_flow_style=False, width=1000)
    return f"{GENERATED}\n{body}"


def _system_section(system: SourceSystem) -> list[str]:
    lines = [
        "",
        f"## {system.domain} / {system.name}",
        "",
        f"Kind: {system.kind}. Owner: {system.owner}.",
    ]
    if system.kind in FILE_KINDS:
        lines.append(
            f"Raw schema: `{system.raw_volume['schema']}`. Files land in a volume here as "
            "delivered, and bronze reads them from it. Each table names its volume."
        )
    if system.kind == DATABASE_KIND:
        engine = f" ({system.engine})" if system.engine else ""
        lines.append(
            f"Foreign catalog: `{system.foreign_catalog}`{engine}. Tables load straight to bronze."
        )
    lines += ["", "| Delivery | When |", "| --- | --- |"]
    for name in sorted(system.deliveries):
        detail = system.deliveries[name]
        when = f"cron `{detail['schedule']}`" if detail.get("schedule") else str(detail["trigger"])
        lines.append(f"| {name} | {when} |")
    lines += [
        "",
        "| Table | Delivery | Requested by | Reads | Load | Bronze | Technical owner |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for table in sorted(system.tables, key=lambda item: item.config.pipeline_id):
        config = table.config
        lines.append(
            f"| {config.pipeline_id} | {table.delivery} | {table.requested_by or '—'} | "
            f"{_reads(config)} | {config.load_method} | "
            f"{config.bronze_schema}.{config.bronze_table} | "
            f"{config.technical_owner} |"
        )
    lines += ["", "```mermaid", "flowchart LR"]
    for name in sorted(system.deliveries):
        lines.append(f"  {node_id(system.name, name)}{{{{{name}}}}}")
    for table in sorted(system.tables, key=lambda item: item.config.pipeline_id):
        config = table.config
        lines.append(
            f"  {node_id(system.name, table.delivery)} -->|{table.requested_by or system.name}| "
            f"{node_id(config.pipeline_id)}[{config.pipeline_id}]"
        )
        bronze = node_id(config.bronze_schema, config.bronze_table)
        lines.append(
            f"  {node_id(config.pipeline_id)} --> {bronze}"
            f"[{config.bronze_schema}.{config.bronze_table}]"
        )
    lines.append("```")
    return lines


def _reads(config: PipelineConfig) -> str:
    """Where a table's data comes from, without the environment's catalog."""

    if config.load_method == "database_table":
        return f"{config.source_table} ({config.source_mode})"
    if config.load_method == "volume_files":
        parts = [part for part in config.path.split("/") if part]
        return f"volume {parts[2]}.{parts[3]}/{'/'.join(parts[4:])} ({config.file_format})"
    return f"{config.path} ({config.file_format})"


def node_id(*parts: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", "_".join(parts))
