"""Project structure: who owns silver and gold, what each table depends on, and the map.

Layout under ``<root>`` (``framework_projects``)::

    <domain>/<project>/project.yaml    silver and gold tables, their triggers, deadlines
    <domain>/<project>/PROJECT_MAP.md  generated
    <root>/PROJECTS_INDEX.md           generated: every project and every cross-project edge

Bronze belongs to a source system in the ingestion bundle. A project reads bronze tables and
owns silver and gold tables. A table name is owned by one project: no other project may create a
table with the same layer and name.

References in ``triggered_by`` and ``reads``::

    <source_system>.<table>            a bronze table in the ingestion bundle
    silver.<name> / gold.<name>        a table of this project
    <project>.silver.<name>            a table of another project

A table may only depend on tables in lower layers. ``triggered_by`` is what fires its job.
``reads`` is read without waiting. No cluster is used.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from lakeflow_framework.config import EMAIL, IDENTIFIER, ConfigValidationError
from lakeflow_framework.ingestion import SourceTable, load_sources

PROJECT_FILE = "project.yaml"
MAP_NAME = "PROJECT_MAP.md"
INDEX_NAME = "PROJECTS_INDEX.md"
GENERATED_NOTE = "Generated by `lakeflow-framework projects`. Do not edit."
RANK = {"bronze": 0, "silver": 1, "gold": 2}
OWNED_LAYERS = ("silver", "gold")
ON_MISS = ("alert", "run_stale")
TIME = re.compile(r"^([01]\d|2[0-3]):[0-5]\d$")


@dataclass
class ProjectTable:
    layer: str
    name: str
    triggered_by: list[str]
    reads: list[str]
    deadline: dict[str, str] | None = None


@dataclass
class Project:
    name: str
    domain: str
    owner: str
    path: Path
    tables: list[ProjectTable] = field(default_factory=list)


def load_projects(
    root: Path, ingestion: Path
) -> tuple[list[Project], dict[tuple[str, str], SourceTable]]:
    """Read every project and check it against the ingestion bundle and the other projects.

    Returns the projects and the bronze tables they can read. Raises one error with every problem.
    """

    errors: list[str] = []
    bronze = _bronze_index(ingestion, errors)
    projects: list[Project] = []
    for path in sorted(root.glob(f"*/*/{PROJECT_FILE}")):
        project = _read_project(path, path.parent.parent.name, path.parent.name, errors)
        if project is not None:
            projects.append(project)
    errors.extend(_duplicate_tables(projects))
    errors.extend(_check_references(projects, bronze))
    errors.extend(_project_cycles(projects))
    if errors:
        raise ConfigValidationError(errors)
    return projects, bronze


def render_files(
    projects: list[Project], bronze: dict[tuple[str, str], SourceTable]
) -> dict[str, str]:
    """Generated files by path under the projects root."""

    files = {INDEX_NAME: _render_index(projects)}
    for project in projects:
        relative = f"{project.domain}/{project.name}/{MAP_NAME}"
        files[relative] = _render_project(project, projects, bronze)
    return files


def generate(root: Path, ingestion: Path, check: bool = False) -> list[str]:
    """Write the project maps. With ``check``, change nothing. Returns stale paths."""

    projects, bronze = load_projects(root, ingestion)
    stale: list[str] = []
    for relative, text in render_files(projects, bronze).items():
        target = root / relative
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            stale.append(relative)
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
    return sorted(stale)


def new_project(root: Path, domain: str, project: str, *, owner: str) -> Path:
    """Create a project folder: a small bundle file and an empty ``project.yaml``."""

    problems = [
        f"{key} must be an identifier, not {value!r}"
        for key, value in {"domain": domain, "project": project}.items()
        if not IDENTIFIER.match(value)
    ]
    if not EMAIL.match(owner):
        problems.append("owner must be an email address")
    if problems:
        raise ConfigValidationError(problems)
    folder = root / domain / project
    target = folder / PROJECT_FILE
    if target.exists():
        raise ConfigValidationError([f"{target} already exists"])
    folder.mkdir(parents=True, exist_ok=True)
    target.write_text(
        f"project: {project}\ndomain: {domain}\nowner: {owner}\n\n"
        "# Reference bronze as <source_system>.<table> (see SOURCE_MAP.md in framework_ingestion),\n"
        "# your own tables as silver.<name>, and another project's as <project>.silver.<name>.\n"
        "silver: {}\ngold: {}\n",
        encoding="utf-8",
    )
    (folder / "databricks.yml").write_text(_BUNDLE_FILE.format(project=project), encoding="utf-8")
    return target


