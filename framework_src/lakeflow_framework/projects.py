def _bronze_index(ingestion: Path, errors: list[str]) -> dict[tuple[str, str], SourceTable]:
    if not (ingestion / "sources").is_dir():
        errors.append(f"{ingestion}: no sources folder; point --sources at the ingestion bundle")
        return {}
    try:
        systems = load_sources(ingestion)
    except ConfigValidationError as exc:
        errors.extend(f"ingestion: {error}" for error in exc.errors)
        return {}
    return {
        (system.name, table.config.bronze_table): table
        for system in systems
        for table in system.tables
    }


def _read_project(path: Path, domain: str, name: str, errors: list[str]) -> Project | None:
    try:
        document = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        errors.append(f"{path}: {exc}")
        return None
    if not isinstance(document, dict):
        errors.append(f"{path}: the document must be a mapping")
        return None
    found: list[str] = []
    if document.get("project") != name:
        found.append(f"{path}: project must be {name}, the folder name")
    if document.get("domain") != domain:
        found.append(f"{path}: domain must be {domain}, the folder name")
    owner = str(document.get("owner") or "")
    if not EMAIL.match(owner):
        found.append(f"{path}: owner must be an email address")
    project = Project(name, domain, owner, path)
    if "TODO" in path.read_text(encoding="utf-8"):
        found.append(f"{path}: replace every TODO")
    for layer in OWNED_LAYERS:
        section = document.get(layer) or {}
        if not isinstance(section, dict):
            found.append(f"{path}: {layer} must be a mapping of table name to its settings")
            continue
        for table_name, settings in section.items():
            table = _read_table(path, layer, str(table_name), settings, found)
            if table is not None:
                project.tables.append(table)
    errors.extend(found)
    return None if found else project


def _read_table(
    path: Path, layer: str, name: str, settings: Any, found: list[str]
) -> ProjectTable | None:
    label = f"{path}: {layer}.{name}"
    if not IDENTIFIER.match(name):
        found.append(f"{label}: the name must be an identifier")
        return None
    if not isinstance(settings, dict):
        found.append(f"{label}: needs triggered_by")
        return None
    problems = len(found)
    lists: dict[str, list[str]] = {}
    for key in ("triggered_by", "reads"):
        value = settings.get(key) or []
        if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
            found.append(f"{label}: {key} must be a list of table references")
            value = []
        lists[key] = list(value)
    if not lists["triggered_by"]:
        found.append(f"{label}: triggered_by needs at least one table")
    deadline = settings.get("deadline")
    if deadline is not None:
        if not isinstance(deadline, dict) or not TIME.match(str(deadline.get("at") or "")):
            found.append(f"{label}: deadline.at must be a time such as 07:00")
        elif deadline.get("on_miss", "alert") not in ON_MISS:
            found.append(f"{label}: deadline.on_miss must be one of {', '.join(ON_MISS)}")
        else:
            deadline = {"at": str(deadline["at"]), "on_miss": str(deadline.get("on_miss", "alert"))}
    return (
        None
        if len(found) > problems
        else ProjectTable(layer, name, lists["triggered_by"], lists["reads"], deadline)
    )


def _duplicate_tables(projects: list[Project]) -> list[str]:
    errors: list[str] = []
    owner: dict[tuple[str, str], Project] = {}
    names: dict[str, Project] = {}
    for project in projects:
        if project.name in names:
            errors.append(
                f"{project.path}: project {project.name} is also defined in {names[project.name].path}"
            )
        names[project.name] = project
        for table in project.tables:
            key = (table.layer, table.name)
            first = owner.get(key)
            if first is not None and first.name != project.name:
                errors.append(
                    f"{project.path}: {table.layer}.{table.name} is already owned by "
                    f"{first.name}; read it instead of creating it again"
                )
            owner.setdefault(key, project)
    return errors


def _check_references(
    projects: list[Project], bronze: dict[tuple[str, str], SourceTable]
) -> list[str]:
    errors: list[str] = []
    by_name = {project.name: project for project in projects}
    for project in projects:
        for table in project.tables:
            for key in ("triggered_by", "reads"):
                for ref in getattr(table, key):
                    problem = _reference_problem(ref, project, table, by_name, bronze)
                    if problem:
                        errors.append(
                            f"{project.path}: {table.layer}.{table.name} {key}: {problem}"
                        )
    return errors


def _reference_problem(
    ref: str,
    project: Project,
    table: ProjectTable,
    by_name: dict[str, Project],
    bronze: dict[tuple[str, str], SourceTable],
) -> str | None:
    parts = ref.split(".")
    if len(parts) == 2 and parts[0] in OWNED_LAYERS:
        layer, name = parts
        target = _find(project, layer, name)
        if target is None:
            return f"{ref} is not a table of this project"
    elif len(parts) == 2:
        if parts not in [list(key) for key in bronze]:
            return f"{ref} is not a bronze table in the ingestion bundle"
        layer = "bronze"
    elif len(parts) == 3 and parts[1] in OWNED_LAYERS:
        other, layer, name = parts
        if other == project.name:
            return f"{ref} is your own table; write {layer}.{name}"
        owner = by_name.get(other)
        if owner is None or _find(owner, layer, name) is None:
            return f"{ref} is not a table of project {other}"
    else:
        return f"{ref} must be <source_system>.<table>, <layer>.<name>, or <project>.<layer>.<name>"
    if RANK[layer] >= RANK[table.layer]:
        return f"{ref} is {layer}; a {table.layer} table can only depend on lower layers"
    return None


def _find(project: Project, layer: str, name: str) -> ProjectTable | None:
    return next((t for t in project.tables if t.layer == layer and t.name == name), None)


def _upstream_projects(project: Project) -> set[str]:
    found: set[str] = set()
    for table in project.tables:
        for ref in [*table.triggered_by, *table.reads]:
            parts = ref.split(".")
            if len(parts) == 3:
                found.add(parts[0])
    return found


def _project_cycles(projects: list[Project]) -> list[str]:
    graph = {project.name: _upstream_projects(project) for project in projects}
    errors: list[str] = []
    state: dict[str, int] = {}

    def visit(name: str, trail: list[str]) -> None:
        state[name] = 1
        for upstream in sorted(graph.get(name, ())):
            if state.get(upstream) == 1:
                cycle = (
                    [*trail[trail.index(upstream) :], upstream]
                    if upstream in trail
                    else [name, upstream]
                )
                errors.append("projects depend on each other in a loop: " + " -> ".join(cycle))
            elif state.get(upstream) is None and upstream in graph:
                visit(upstream, [*trail, upstream])
        state[name] = 2

    for name in sorted(graph):
        if state.get(name) is None:
            visit(name, [name])
    return errors


def _describe(ref: str, project: Project, bronze: dict[tuple[str, str], SourceTable]) -> str:
    parts = ref.split(".")
    if len(parts) == 2 and parts[0] not in OWNED_LAYERS:
        found = bronze.get((parts[0], parts[1]))
        if found is not None:
            return f"`{ref}` (bronze, {found.delivery} delivery, requested by {found.requested_by})"
    if len(parts) == 3:
        return f"`{ref}` (project {parts[0]})"
    return f"`{ref}`"


def _render_project(
    project: Project, projects: list[Project], bronze: dict[tuple[str, str], SourceTable]
) -> str:
    lines = [
        f"# Project map: {project.domain} / {project.name}",
        "",
        f"{GENERATED_NOTE} Change `{PROJECT_FILE}` and regenerate.",
        "",
        f"Owner: {project.owner}.",
    ]
    for layer in OWNED_LAYERS:
        tables = sorted((t for t in project.tables if t.layer == layer), key=lambda t: t.name)
        lines += ["", f"## {layer.capitalize()}", ""]
        if not tables:
            lines.append(f"No {layer} tables yet.")
            continue
        lines += ["| Table | Triggered by | Reads | Deadline |", "| --- | --- | --- | --- |"]
        for table in tables:
            fired = ", ".join(_describe(r, project, bronze) for r in table.triggered_by)
            read = ", ".join(_describe(r, project, bronze) for r in table.reads) or "-"
            lines.append(f"| {table.name} | {fired} | {read} | {_deadline(table)} |")
    warnings = _warnings(project)
    lines += ["", "## Checks", ""]
    lines += [f"- {text}" for text in warnings] or ["- None."]
    used_by = _used_by(project, projects)
    lines += ["", "## Used by other projects", ""]
    lines += [f"- {text}" for text in used_by] or ["- None."]
    lines += ["", "```mermaid", "flowchart LR"]
    for table in sorted(project.tables, key=lambda t: (RANK[t.layer], t.name)):
        node = _node(table.layer, table.name)
        lines.append(f"  {node}[{table.layer}.{table.name}]")
        for ref in table.triggered_by:
            lines.append(f"  {_ref_node(ref, project)} --> {node}")
        for ref in table.reads:
            lines.append(f"  {_ref_node(ref, project)} -.-> {node}")
    lines.append("```")
    return "\n".join(lines) + "\n"


def _warnings(project: Project) -> list[str]:
    found: list[str] = []
    for table in sorted(project.tables, key=lambda t: (RANK[t.layer], t.name)):
        if len(table.triggered_by) > 1 and table.deadline is None:
            found.append(
                f"{table.layer}.{table.name} waits for {len(table.triggered_by)} tables and has no "
                "deadline; a late upstream stalls it"
            )
    return found


def _used_by(project: Project, projects: list[Project]) -> list[str]:
    found: list[str] = []
    for other in projects:
        if other.name == project.name:
            continue
        for table in other.tables:
            for ref in [*table.triggered_by, *table.reads]:
                if ref.startswith(f"{project.name}."):
                    found.append(f"`{ref}` is used by {other.name}: {table.layer}.{table.name}")
    return sorted(found)


def _render_index(projects: list[Project]) -> str:
    lines = [
        "# Projects index",
        "",
        f"{GENERATED_NOTE}",
        "",
        "| Project | Domain | Owner | Silver | Gold | Reads from projects |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for project in sorted(projects, key=lambda p: (p.domain, p.name)):
        count = {
            layer: sum(1 for t in project.tables if t.layer == layer) for layer in OWNED_LAYERS
        }
        upstream = ", ".join(sorted(_upstream_projects(project))) or "-"
        lines.append(
            f"| {project.name} | {project.domain} | {project.owner} | "
            f"{count['silver']} | {count['gold']} | {upstream} |"
        )
    return "\n".join(lines) + "\n"


def _deadline(table: ProjectTable) -> str:
    if table.deadline is None:
        return "-"
    return f"{table.deadline['at']} UTC, {table.deadline['on_miss'].replace('_', ' ')}"


def _ref_node(ref: str, project: Project) -> str:
    parts = ref.split(".")
    if len(parts) == 2 and parts[0] in OWNED_LAYERS:
        return _node(*parts)
    return f"{_node(*parts)}([{ref}])"


def _node(*parts: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", "_".join(parts))
