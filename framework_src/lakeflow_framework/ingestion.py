def _names(values: dict[str, str]) -> None:
    bad = [
        f"{key} must be an identifier, not {value!r}"
        for key, value in values.items()
        if not IDENTIFIER.match(value)
    ]
    if bad:
        raise ConfigValidationError(bad)


def _reads(config: PipelineConfig) -> str:
    """Where a table's data comes from, without the environment's catalog."""

    if config.load_method == "database_table":
        return f"{config.source_table} ({config.source_mode})"
    if config.load_method == "volume_files":
        parts = [part for part in config.path.split("/") if part]
        return f"volume {parts[2]}.{parts[3]}/{'/'.join(parts[4:])} ({config.file_format})"
    return f"{config.path} ({config.file_format})"


def _node(*parts: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", "_".join(parts))
